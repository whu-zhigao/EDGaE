#!/usr/bin/env python3
"""Generate combined real-topology trace tables for the manuscript."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path
from typing import Dict, Iterable


ROOT = Path(__file__).resolve().parents[1]
WWW_DIR = ROOT / "www"


DATASETS = {
    "web-google": {
        "summary": str(WWW_DIR / "www2027-real-trace-web-google-summary-v3.csv"),
        "topology": "SNAP reservoir subgraph",
        "vertices": 12000,
        "edges": 13759,
    },
    "amazon0601": {
        "summary": str(WWW_DIR / "www2027-real-trace-amazon-summary-v2.csv"),
        "topology": "SNAP reservoir subgraph",
        "vertices": 12000,
        "edges": 12676,
    },
    "wiki-talk": {
        "summary": str(WWW_DIR / "www2027-real-trace-wiki-summary-v2.csv"),
        "topology": "SNAP reservoir subgraph",
        "vertices": 12000,
        "edges": 26301,
    },
    "ogbn-arxiv": {
        "summary": str(WWW_DIR / "www2027-real-trace-arxiv-summary-v2.csv"),
        "topology": "official full OGB topology",
        "vertices": 169343,
        "edges": 1157799,
    },
}


def load(path: Path) -> Dict[str, dict]:
    with path.open(newline="", encoding="utf-8") as stream:
        return {
            f"{row['block']}|{row['control']}": row
            for row in csv.DictReader(stream)
        }


def value(row: dict, key: str, digits: int = 3) -> str:
    text = row.get(f"{key}_mean", "")
    return "--" if text == "" else f"{float(text):.{digits}f}"


def interval(row: dict, key: str, digits: int = 3) -> str:
    fields = [row.get(f"{key}_{suffix}", "") for suffix in ["mean", "ci95_low", "ci95_high"]]
    if any(field == "" for field in fields):
        return "--"
    mean, low, high = map(float, fields)
    return f"{mean:.{digits}f} [{low:.{digits}f}, {high:.{digits}f}]"


def mb(row: dict, key: str) -> str:
    return f"{float(row[f'{key}_mean']) / 1e6:.2f}"


def generate(summaries: Dict[str, Dict[str, dict]]) -> str:
    lines = [
        "% AUTO-GENERATED by experiments/generate_multi_real_trace_tables.py.",
        "% Evidence level: trace-driven simulation on real graph topologies.",
        "\\section{Real-Topology Trace-Driven Results}",
        "\\label{app:real-trace-results}",
        "",
        "\\begin{table}[t]",
        "\\caption{Real topologies used by the trace-driven evaluation. SNAP topologies use a deterministic 12{,}000-vertex reservoir subgraph; \\texttt{ogbn-arxiv} uses the complete official topology.}",
        "\\label{tbl:real-topologies}",
        "\\centering",
        "\\small",
        "\\begin{tabular}{lrrl}",
        "\\toprule",
        "Dataset & Vertices & Edges & Source\\\\",
        "\\midrule",
    ]
    for dataset, spec in DATASETS.items():
        lines.append(
            f"\\texttt{{{dataset}}} & {spec['vertices']:,} & "
            f"{spec['edges']:,} & {spec['topology']}\\\\"
        )
    lines.extend([
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
        "\\begin{table*}[t]",
        "\\caption{Cache stability on four real topologies. Each point is the mean over five independent sampler seeds; brackets give bootstrap 95\\% confidence intervals. Savings are application-level feature bytes relative to the server-centric trace.}",
        "\\label{tbl:real-cache-stability-all}",
        "\\centering",
        "\\small",
        "\\begin{tabular}{llrrrr}",
        "\\toprule",
        "Dataset & $K$ & Hit rate (95\\% CI) & Top-$k$ Jaccard & $C_{\\mathrm{edg}}$ (MB) & Savings\\\\",
        "\\midrule",
    ])
    cache_keys = ["K=1", "K=2", "K=4", "K=8", "K=16", "K=full-trace"]
    for dataset, rows in summaries.items():
        server = float(rows["cache-stability|K=full-trace"]["C_srv_bytes_mean"])
        for i, key in enumerate(cache_keys):
            row = rows[f"cache-stability|{key}"]
            edge = float(row["C_edg_bytes_mean"])
            label = "$\\infty$" if key == "K=full-trace" else key.removeprefix("K=")
            first = dataset if i == 0 else ""
            lines.append(
                f"\\texttt{{{first}}} & {label} & {interval(row, 'cache_hit_rate')} & "
                f"{value(row, 'topk_jaccard')} & {edge/1e6:.2f} & "
                f"{100*(1-edge/server):.1f}\\%\\\\"
            )
        if dataset != list(summaries)[-1]:
            lines.append("\\midrule")
    lines.extend([
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table*}",
        "",
        "\\begin{table*}[t]",
        "\\caption{Partition feasibility and residual feature bytes on the real topologies. All policies use the same cache budget and five sampler seeds. EDGaE enforces the integer load target when a memory-feasible worker exists; fallback rows are reported separately in the raw artifact.}",
        "\\label{tbl:real-partition-all}",
        "\\centering",
        "\\small",
        "\\begin{tabular}{llrrrrr}",
        "\\toprule",
        "Dataset & Policy & Vert.\\ rep. & Edge rep. & Imbalance & $C_{\\mathrm{edg}}$ (MB) & Hit rate\\\\",
        "\\midrule",
    ])
    partition_keys = ["even", "random", "METIS-like", "PaGraph-style", "EDGaE"]
    for dataset, rows in summaries.items():
        for i, key in enumerate(partition_keys):
            row = rows[f"partition-policy|{key}"]
            first = dataset if i == 0 else ""
            lines.append(
                f"\\texttt{{{first}}} & {key} & "
                f"{value(row, 'replication_factor_vertices')} & "
                f"{value(row, 'replication_factor_edges')} & "
                f"{value(row, 'load_imbalance')} & {mb(row, 'C_edg_bytes')} & "
                f"{value(row, 'cache_hit_rate')}\\\\"
            )
        if dataset != list(summaries)[-1]:
            lines.append("\\midrule")
    lines.extend([
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table*}",
        "",
        "\\begin{table}[t]",
        "\\caption{Trace-level component ablation. Pipeline changes overlap rather than bytes, so +RCS and +RCSP have identical data-path results.}",
        "\\label{tbl:real-component-all}",
        "\\centering",
        "\\small",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "Dataset & Vert.\\ rep. & Imbalance & $C_{\\mathrm{edg}}$ (MB) & Hit rate\\\\",
        "\\midrule",
    ])
    for dataset, rows in summaries.items():
        row = rows["component-ablation|+RCS"]
        lines.append(
            f"\\texttt{{{dataset}}} & {value(row, 'replication_factor_vertices')} & "
            f"{value(row, 'load_imbalance')} & {mb(row, 'C_edg_bytes')} & "
            f"{value(row, 'cache_hit_rate')}\\\\"
        )
    lines.extend([
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
        "\\noindent\\textbf{Evidence boundary.} These rows are exact trace-driven data-path simulations. They establish cache selection, replication, load, feasibility, and application-byte effects, but they are not wall-clock, energy, accuracy, or Raspberry Pi measurements. The \\texttt{wiki-talk} subgraph is a useful negative feasibility case: under the configured memory ceiling, the median run reports 438 fallback assignments, so the high replication and imbalance are reported rather than hidden.",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "output",
        nargs="?",
        default=str(WWW_DIR / "www2027-real-trace-tables.tex"),
    )
    args = parser.parse_args()
    summaries = {
        dataset: load(Path(spec["summary"]))
        for dataset, spec in DATASETS.items()
    }
    Path(args.output).write_text(generate(summaries), encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

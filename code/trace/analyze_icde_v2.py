def fnum(value):
    try:
        return float(value)
    except (TypeError, ValueError):
        return math.nan


def bootstrap_ci(values, samples=5000, seed=12345):
    if not values:
        return math.nan, math.nan
    rng = random.Random(seed)
    means = []
    n = len(values)
    for _ in range(samples):
        means.append(sum(values[rng.randrange(n)] for _ in range(n)) / n)
    means.sort()
    return means[int(0.025 * samples)], means[int(0.975 * samples)]


def aggregate(rows):
    groups = defaultdict(list)
    for row in rows:
        if row["measurement_valid"] != "True":
            continue
        key = (row["block"], row["dataset"], row["control"])
        groups[key].append(row)
    summary = {}
    for (block, dataset, control), items in sorted(groups.items()):
        entry = {"n_seeds": len(items)}
        for field in [
            "C_srv_bytes", "C_edg_bytes", "cache_hit_rate", "cache_coverage",
            "topk_jaccard", "boundary_gap", "replication_factor_vertices",
            "replication_factor_edges", "load_imbalance", "fallbacks",
            "feasibility_failures", "T_partition_s", "T_presample_s",
            "T_cache_s", "T_pre_total_s", "graph_vertices", "graph_edges",
            "adaptive_k", "assignment_agreement", "replica_jaccard",
            "two_tier_beta",
        ]:
            values = [v for v in (fnum(r.get(field)) for r in items) if not math.isnan(v)]
            if not values:
                continue
            mean = sum(values) / len(values)
            std = (sum((v - mean) ** 2 for v in values) / max(1, len(values) - 1)) ** 0.5
            low, high = bootstrap_ci(values)
            entry[field] = {"mean": mean, "std": std, "ci95_low": low, "ci95_high": high}
        summary[f"{block}|{dataset}|{control}"] = entry
    return summary


def get(summary, block, dataset, control, field):
    return summary[f"{block}|{dataset}|{control}"][field]


def generate_tables(summary, outdir):
    rows = []
    for dataset in DATASETS:
        vertex_entry = get(summary, "partition-policy", dataset, "EDGaE", "graph_vertices")
        edge_entry = get(summary, "partition-policy", dataset, "EDGaE", "graph_edges")
        source = {
            "web-google": "SNAP 12k reservoir", "amazon0601": "SNAP 12k reservoir",
            "wiki-talk": "SNAP 12k reservoir", "ogbn-arxiv": "OGB official (complete)",
            "amazon0601-full": "SNAP official (complete)",
            "web-google-full": "SNAP official (complete)",
            "wiki-talk-full": "SNAP official (complete)",
        }[dataset]
        rows.append(
            "\\texttt{%s} & %s & %s & %s\\\\" % (
                LABEL[dataset], f"{int(vertex_entry['mean']):,}",
                f"{int(edge_entry['mean']):,}", source,
            )
        )
    (outdir / "tab-topologies.tex").write_text(
        "% AUTO-GENERATED by experiments/analyze_icde_v2.py\n"
        "\\begin{tabular}{@{}lrrl@{}}\n\\toprule\n"
        "Topology & Vertices & Unique undirected edges & Source\\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n"
    )

    lines = []
    for dataset in DATASETS:
        hits = {}
        for k in K_VALUES:
            control = "K=full-trace" if k == "full" else f"K={k}"
            hits[k] = get(summary, "cache-stability", dataset, control, "cache_hit_rate")["mean"]
        chosen = None
        for i, k in enumerate(K_VALUES[:-2]):
            nxt = K_VALUES[i + 1]
            if hits[nxt] > 0 and (hits[nxt] - hits[k]) / hits[nxt] < 0.02:
                chosen = nxt
                break
        if chosen is None:
            chosen = 16
        oracle, k2 = hits["full"], hits[2]
        lines.append(
            "\\texttt{%s} & %d & %.1f & %.1f & %.1f & %+.1f\\\\" % (
                LABEL[dataset], chosen, 100 * hits[chosen], 100 * k2,
                100 * oracle, 100 * (hits[chosen] - k2) / max(k2, 1e-9),
            )
        )
    (outdir / "tab-adaptive-k.tex").write_text(
        "% AUTO-GENERATED by experiments/analyze_icde_v2.py\n"
        "\\begin{tabular}{@{}lrrrrr@{}}\n\\toprule\n"
        "Topology & $K^\\star$ & Hit (\\%) & Hit $K{=}2$ (\\%) & Oracle (\\%) & Gain vs.\\ $K{=}2$ (\\%)\\\\\n"
        "\\midrule\n" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n"
    )

    lines = []
    for dataset in DATASETS:
        edgae = summary.get(f"preprocess|{dataset}|EDGaE-K16") or summary[f"partition-policy|{dataset}|EDGaE"]
        t_pre = edgae["T_pre_total_s"]["mean"]
        delta_c = edgae["C_srv_bytes"]["mean"] - edgae["C_edg_bytes"]["mean"]
        # Replica shipping bytes: s_v = 8 B (id + metadata), s_e = 8 B
        # (two int32 endpoints), from the measured replication factors.
        vertices = edgae["graph_vertices"]["mean"]
        edges = edgae["graph_edges"]["mean"]
        ship_bytes = (
            edgae["replication_factor_vertices"]["mean"] * vertices * 8
            + edgae["replication_factor_edges"]["mean"] * edges * 8
        )
        cells = []
        for _, b in BANDWIDTHS:
            h = math.ceil((t_pre * b + ship_bytes) / delta_c) if delta_c > 0 else math.inf
            cells.append("--" if not math.isfinite(h) else str(int(h)))
        lines.append(
            "\\texttt{%s} & %.2f & %.2f & %.2f & %.2f & %.1f & %s & %s & %s\\\\" % (
                LABEL[dataset], edgae["T_partition_s"]["mean"],
                edgae["T_presample_s"]["mean"], edgae["T_cache_s"]["mean"],
                delta_c / 1e6, ship_bytes / 1e6, cells[0], cells[1], cells[2],
            )
        )
    (outdir / "tab-preprocessing.tex").write_text(
        "% AUTO-GENERATED by experiments/analyze_icde_v2.py\n"
        "\\begin{tabular}{@{}lrrrrrrrr@{}}\n\\toprule\n"
        "Topology & $T_{\\mathrm{part}}$ (s) & $T_{\\mathrm{pre}}$ (s) & "
        "$T_{\\mathrm{cache}}$ (s) & $\\Delta C$ (MB) & "
        "Ship (MB) & "
        "$H^\\star_{10}$ & $H^\\star_{100}$ & $H^\\star_{1000}$\\\\\n"
        "\\midrule\n" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n"
    )

    lines = []
    for dataset in DATASETS:
        cells = []
        for comp in COMPONENTS:
            entry = summary[f"component-ablation|{dataset}|{comp}"]["C_edg_bytes"]
            cells.append(f"{entry['mean'] / 1e6:.2f}")
        lines.append(f"\\texttt{{{LABEL[dataset]}}} & " + " & ".join(cells) + r"\\")
    (outdir / "tab-ablation.tex").write_text(
        "% AUTO-GENERATED by experiments/analyze_icde_v2.py\n"
        "\\begin{tabular}{@{}lrrrrr@{}}\n\\toprule\n"
        "Topology & DGL-E & +R & +RC & +RCS & +RCSP\\\\\n\\midrule\n"
        + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n"
    )

    # ---- sampler sensitivity ----------------------------------------------
    sens_columns = [
        ("d=1", "f=2,d=1,non-uniform"), ("d=3", "f=2,d=3,non-uniform"),
        ("f=4", "f=4,d=2,non-uniform"), ("f=8", "f=8,d=2,non-uniform"),
        ("uni.", "f=2,d=2,uniform"),
    ]
    lines = []
    for dataset in DATASETS:
        cells = []
        for _, control in sens_columns:
            key = f"sampler-sensitivity|{dataset}|{control}"
            if key in summary and "assignment_agreement" in summary[key]:
                cells.append(f"{summary[key]['assignment_agreement']['mean']:.2f}")
            else:
                cells.append("--")
        lines.append(f"\\texttt{{{LABEL[dataset]}}} & " + " & ".join(cells) + r"\\")
    (outdir / "tab-sensitivity.tex").write_text(
        "% AUTO-GENERATED by experiments/analyze_icde_v2.py\n"
        "\\begin{tabular}{@{}lrrrrr@{}}\n\\toprule\n"
        "Topology & $d{=}1$ & $d{=}3$ & $f{=}4$ & $f{=}8$ & uniform\\\\\n"
        "\\midrule\n" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n"
    )

    # ---- cache-regime decomposition ----------------------------------------
    lines = []
    for dataset in DATASETS:
        pw_k16 = get(summary, "online-cache", dataset, "static-K16", "cache_hit_rate")["mean"]
        pw_oracle = get(summary, "online-cache", dataset, "static-full", "cache_hit_rate")["mean"]
        global_static = summary[f"two-tier|{dataset}|beta=0.0"]["cache_hit_rate"]["mean"]
        global_lfu = summary[f"two-tier|{dataset}|beta=1.0"]["cache_hit_rate"]["mean"]
        best_beta, best_hit = 0.0, global_static
        for beta in [0.25, 0.5, 0.75]:
            hit = summary[f"two-tier|{dataset}|beta={beta}"]["cache_hit_rate"]["mean"]
            if hit > best_hit:
                best_beta, best_hit = beta, hit
        lines.append(
            "\\texttt{%s} & %.3f & %.3f & %.3f & %.3f & %.2f & %.3f\\\\" % (
                LABEL[dataset], pw_k16, pw_oracle, global_static, global_lfu,
                best_beta, best_hit,
            )
        )
    (outdir / "tab-cache-regimes.tex").write_text(
        "% AUTO-GENERATED by experiments/analyze_icde_v2.py\n"
        "\\begin{tabular}{@{}lrrrrrr@{}}\n\\toprule\n"
        "Topology & \\multicolumn{2}{c}{Per-worker static} & "
        "\\multicolumn{2}{c}{Centralized} & \\multicolumn{2}{c}{Best two-tier}\\\\\n"
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\n"
        " & $K{=}16$ & oracle & static & LFU & $\\beta$ & hit\\\\\n"
        "\\midrule\n" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n"
    )


def grouped_bar(ax, datasets, controls, block, summary, field, ylabel):
    width = 0.8 / len(controls)
    for j, control in enumerate(controls):
        xs, ys, errs = [], [], []
        for i, dataset in enumerate(datasets):
            entry = get(summary, block, dataset, control, field)
            xs.append(i + (j - len(controls) / 2 + 0.5) * width)
            ys.append(entry["mean"])
            errs.append([entry["mean"] - entry["ci95_low"], entry["ci95_high"] - entry["mean"]])
        ax.bar(xs, ys, width=width, label=POLICY_LABEL.get(control, control),
               yerr=list(zip(*errs)), capsize=1.5, error_kw={"lw": 0.7})
    ax.set_xticks(range(len(datasets)))
    ax.set_xticklabels([LABEL[d] for d in datasets], rotation=28, ha="right", fontsize=7)
    ax.set_ylabel(ylabel, fontsize=8)
    ax.tick_params(axis="y", labelsize=7)


def generate_figures(summary, figdir):
    plt.rcParams.update({"font.size": 7.5, "axes.titlesize": 8, "legend.fontsize": 6.5,
                         "pdf.fonttype": 42})

    fig, axes = plt.subplots(2, 2, figsize=(7.0, 3.0))
    grouped_bar(axes[0][0], SUBGRAPHS, POLICIES, "partition-policy", summary, "C_edg_bytes", "Residual bytes")
    axes[0][0].set_title("(a) Residual bytes, 12k topologies")
    grouped_bar(axes[0][1], LARGE, POLICIES, "partition-policy", summary, "C_edg_bytes", "Residual bytes")
    axes[0][1].set_title("(b) Residual bytes, full/prefix")
    grouped_bar(axes[1][0], SUBGRAPHS, POLICIES, "partition-policy", summary, "replication_factor_vertices", "Vertex replication")
    axes[1][0].set_title("(c) Replication, 12k topologies")
    grouped_bar(axes[1][1], LARGE, POLICIES, "partition-policy", summary, "replication_factor_vertices", "Vertex replication")
    axes[1][1].set_title("(d) Replication, full/prefix")
    axes[0][0].legend(ncol=3, loc="upper right", frameon=False)
    fig.tight_layout()
    fig.savefig(figdir / "icde-v2-partition.pdf")
    plt.close(fig)

    fig, axes = plt.subplots(1, 2, figsize=(7.0, 1.7), sharex=True)
    for dataset in DATASETS:
        for ax, metric in ((axes[0], "cache_hit_rate"), (axes[1], "topk_jaccard")):
            xs, ys, lo, hi = [], [], [], []
            for k in K_VALUES:
                control = "K=full-trace" if k == "full" else f"K={k}"
                entry = get(summary, "cache-stability", dataset, control, metric)
                xs.append(17 if k == "full" else k)
                ys.append(entry["mean"]); lo.append(entry["ci95_low"]); hi.append(entry["ci95_high"])
            ax.plot(xs, ys, marker="o", ms=2.5, lw=1, label=LABEL[dataset])
            ax.fill_between(xs, lo, hi, alpha=0.15, lw=0)
    for ax in axes:
        ax.set_xscale("log", base=2)
        ax.set_xticks([1, 2, 4, 8, 16]); ax.set_xticklabels([1, 2, 4, 8, 16])
    for ax in axes:
        ax.set_xlabel("$K$")
    axes[0].set_ylabel("Cache hit rate"); axes[1].set_ylabel("Top-$k$ Jaccard")
    axes[0].set_title("(a) Effectiveness vs. $K$", fontsize=7)
    axes[1].set_title("(b) Hot-set recovery vs. $K$", fontsize=7)
    axes[1].legend(ncol=2, frameon=False, loc="lower right")
    fig.tight_layout()
    fig.savefig(figdir / "icde-v2-cache-stability.pdf")
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(3.45, 2.0))
    width = 0.8 / len(ONLINE_POLICIES)
    for j, control in enumerate(ONLINE_POLICIES):
        xs, ys, errs = [], [], []
        for i, dataset in enumerate(DATASETS):
            entry = get(summary, "online-cache", dataset, control, "cache_hit_rate")
            xs.append(i + (j - len(ONLINE_POLICIES) / 2 + 0.5) * width)
            ys.append(entry["mean"])
            errs.append([entry["mean"] - entry["ci95_low"], entry["ci95_high"] - entry["mean"]])
        ax.bar(xs, ys, width=width, label=ONLINE_LABEL[control],
               yerr=list(zip(*errs)), capsize=1.2, error_kw={"lw": 0.6})
    ax.set_xticks(range(len(DATASETS)))
    ax.set_xticklabels([LABEL[d].replace(" ", "\n") for d in DATASETS], fontsize=6.2)
    ax.set_ylabel("Cache hit rate")
    ax.legend(ncol=2, frameon=False, fontsize=6)
    fig.tight_layout()
    fig.savefig(figdir / "icde-v2-online-cache.pdf")
    plt.close(fig)

    # Sampler sensitivity: bytes vs fan-out and vs depth
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 1.6))
    for dataset in DATASETS:
        for ax, axis, controls in (
            (axes[0], "fan-out", ["f=2,d=2,non-uniform", "f=4,d=2,non-uniform", "f=8,d=2,non-uniform"]),
            (axes[1], "depth", ["f=2,d=1,non-uniform", "f=2,d=2,non-uniform", "f=2,d=3,non-uniform"]),
        ):
            xs, ys, lo, hi = [], [], [], []
            for x, control in zip((2, 4, 8) if axis == "fan-out" else (1, 2, 3), controls):
                key = f"sampler-sensitivity|{dataset}|{control}"
                if key not in summary:
                    continue
                entry = summary[key]["C_edg_bytes"]
                xs.append(x); ys.append(entry["mean"] / 1e6)
                lo.append(entry["ci95_low"] / 1e6); hi.append(entry["ci95_high"] / 1e6)
            ax.plot(xs, ys, marker="o", ms=2.5, lw=1, label=LABEL[dataset])
            ax.fill_between(xs, lo, hi, alpha=0.15, lw=0)
    for ax in axes:
        ax.set_yscale("log")
        ax.set_xlabel("fan-out $f$" if ax is axes[0] else "depth $L$")
        ax.tick_params(labelsize=7)
    axes[0].set_xticks([2, 4, 8]); axes[1].set_xticks([1, 2, 3])
    axes[0].set_ylabel("Residual bytes (MB)")
    axes[0].set_title("(a) Sampler fan-out axis ($L{=}2$)", fontsize=7)
    axes[1].set_title("(b) Receptive-field depth axis ($f{=}2$)", fontsize=7)
    axes[1].legend(ncol=2, frameon=False, loc="upper left", fontsize=6)
    fig.tight_layout()
    fig.savefig(figdir / "icde-v2-sensitivity.pdf")
    plt.close(fig)

    # Two-tier cache: hit rate vs mutable fraction beta
    fig, ax = plt.subplots(figsize=(3.45, 2.0))
    for dataset in DATASETS:
        xs, ys, lo, hi = [], [], [], []
        for beta in [0.0, 0.25, 0.5, 0.75, 1.0]:
            key = f"two-tier|{dataset}|beta={beta:.2f}"
            if key not in summary:
                continue
            entry = summary[key]["cache_hit_rate"]
            xs.append(beta); ys.append(entry["mean"])
            lo.append(entry["ci95_low"]); hi.append(entry["ci95_high"])
        ax.plot(xs, ys, marker="o", ms=2.5, lw=1, label=LABEL[dataset])
        ax.fill_between(xs, lo, hi, alpha=0.15, lw=0)
    ax.set_xlabel("mutable hot-tier fraction $\\beta$")
    ax.set_ylabel("Cache hit rate")
    ax.legend(ncol=2, frameon=False, fontsize=6)
    fig.tight_layout()
    fig.savefig(figdir / "icde-v2-two-tier.pdf")
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("results", nargs="?", default="www/icde2027-v2-trace-results.csv")
    parser.add_argument("--preprocess-results", default="www/icde2027-v2-preprocess-results.csv")
    parser.add_argument("--ablation-results", default="www/icde2027-v2-ablation-results.csv")
    parser.add_argument("--extra-results", default="www/icde2027-v2-extra-results.csv")
    parser.add_argument("--sensitivity-results", default="www/icde2027-v2-sensitivity-results.csv")
    parser.add_argument("--online-results", default="www/icde2027-v2-online-results.csv")
    parser.add_argument("--two-tier-results", default="www/icde2027-v2-two-tier-results.csv")
    parser.add_argument("--web-google-complete-results",
                        default="www/icde2027-v2-web-google-complete-results.csv")
    parser.add_argument("--wiki-talk-complete-results",
                        default="www/icde2027-v2-wiki-talk-complete-results.csv")
    parser.add_argument("--root", type=Path, default=Path("."))
    args = parser.parse_args()
    with open(args.results, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    if Path(args.preprocess_results).exists():
        with open(args.preprocess_results, newline="", encoding="utf-8") as f:
            rows += list(csv.DictReader(f))
    if Path(args.ablation_results).exists():
        # Rerun with correct no-cache semantics for DGL-E/+R/+RC; these rows
        # replace the original matrix rows during aggregation.
        with open(args.ablation_results, newline="", encoding="utf-8") as f:
            rows += list(csv.DictReader(f))
        rerun = {(r["dataset"], r["control"], r["seed"]) for r in rows
                 if r["block"] == "component-ablation" and r.get("run_id", "").startswith("ab-")}
        rows = [r for r in rows if not (
            r["block"] == "component-ablation"
            and not r.get("run_id", "").startswith("ab-")
            and (r["dataset"], r["control"], r["seed"]) in rerun
        )]
    if Path(args.sensitivity_results).exists():
        with open(args.sensitivity_results, newline="", encoding="utf-8") as f:
            rows += [r for r in csv.DictReader(f) if r["block"] == "sampler-sensitivity"]
    if Path(args.extra_results).exists():
        with open(args.extra_results, newline="", encoding="utf-8") as f:
            rows += [r for r in csv.DictReader(f) if r["block"] == "two-tier"]
    # Corrected reruns replace the original matrix rows for these controls.
    for rerun_path, blocks in (
        (args.online_results, {"online-cache"}),
        (args.two_tier_results, {"two-tier"}),
        (args.web_google_complete_results,
         {"cache-stability", "partition-policy", "component-ablation",
          "score-sensitivity", "online-cache", "sampler-sensitivity",
          "two-tier", "preprocess"}),
        (args.wiki_talk_complete_results,
         {"cache-stability", "partition-policy", "component-ablation",
          "score-sensitivity", "online-cache", "sampler-sensitivity",
          "two-tier", "preprocess"}),
    ):
        if Path(rerun_path).exists():
            with open(rerun_path, newline="", encoding="utf-8") as f:
                rerun_rows = [r for r in csv.DictReader(f) if r["block"] in blocks]
            rerun = {(r["dataset"], r["control"], r["seed"]) for r in rerun_rows}
            rows = [r for r in rows if not (
                r["block"] in blocks
                and (r["dataset"], r["control"], r["seed"]) in rerun
                and r.get("run_id", "") not in {x["run_id"] for x in rerun_rows}
            )]
            rows += rerun_rows
    summary = aggregate(rows)
    target = args.root / "www/icde2027-v2-summary.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(summary, indent=1))
    generate_tables(summary, args.root / "ICDE")
    generate_figures(summary, args.root / "ICDE/fig")
    print(f"aggregated {len(summary)} groups")


if __name__ == "__main__":
    raise SystemExit(main())

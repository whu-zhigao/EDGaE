#!/usr/bin/env python3
"""Generate manuscript tables from the real-topology trace summary."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path
from typing import Dict


def load_summary(path: Path) -> Dict[str, dict]:
    with path.open(newline="", encoding="utf-8") as stream:
        return {
            f"{row['block']}|{row['control']}": row
            for row in csv.DictReader(stream)
        }


def number(row: dict, key: str, digits: int = 3) -> str:
    value = row.get(f"{key}_mean", "")
    if value == "":
        return "--"
    return f"{float(value):.{digits}f}"


def ci(row: dict, key: str, digits: int = 3) -> str:
    mean = row.get(f"{key}_mean", "")
    low = row.get(f"{key}_ci95_low", "")
    high = row.get(f"{key}_ci95_high", "")
    if not mean or not low or not high:
        return "--"
    return f"{float(mean):.{digits}f} [{float(low):.{digits}f}, {float(high):.{digits}f}]"


def make_table(summary: Dict[str, dict]) -> str:
    cache_keys = ["K=1", "K=2", "K=4", "K=8", "K=16", "K=full-trace"]
    partition_keys = ["even", "random", "METIS-like", "PaGraph-style", "EDGaE"]
    component_keys = ["DGL-E", "+R", "+RC", "+RCS", "+RCSP"]
    score_keys = ["equal-weights", "locality-heavy", "balance-heavy", "memory-heavy"]

    lines = [
        "% AUTO-GENERATED by experiments/generate_real_trace_tables.py.",
        "% Evidence level: trace-driven simulation on a real Web-graph topology.",
        "\\section{Real-Topology Trace-Driven Results}",
        "\\label{app:real-trace-results}",
        "",
        "This appendix reports the trace-driven evidence level on a real Web topology. "
        "The source is the public SNAP \\texttt{web-Google} graph. Because the available "
        "download was truncated, the experiment uses a reproducible prefix of 2{,}820{,}039 "
        "unique undirected edges, reservoir-samples 180{,}000 edges with seed 2027, and "
        "extracts a connected 12{,}000-vertex, 13{,}759-edge subgraph. Vertex IDs are "
        "compactly remapped. All rows use five independent sampler seeds. These are exact "
        "data-path simulations, not wall-clock, energy, or Raspberry Pi measurements.",
        "",
        "\\begin{table}[t]",
        "\\caption{Real-topology cache stability across five sampler seeds.}",
        "\\label{tbl:real-cache-stability}",
        "\\centering",
        "\\small",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "$K$ & Hit rate (95\\% CI) & Jaccard & $C_{\\mathrm{edg}}$ (MB) & Savings\\\\",
        "\\midrule",
    ]
    server_mb = float(summary["cache-stability|K=full-trace"]["C_srv_bytes_mean"]) / 1e6
    for key in cache_keys:
        row = summary[f"cache-stability|{key}"]
        edge_mb = float(row["C_edg_bytes_mean"]) / 1e6
        savings = 100.0 * (1.0 - edge_mb / server_mb)
        label = "$\\infty$" if key == "K=full-trace" else key.removeprefix("K=")
        lines.append(
            f"{label} & {ci(row, 'cache_hit_rate')} & "
            f"{number(row, 'topk_jaccard')} & {edge_mb:.2f} & {savings:.1f}\\%\\\\"
        )
    lines.extend([
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
        "\\begin{table}[t]",
        "\\caption{Real-topology partition feasibility and communication.}",
        "\\label{tbl:real-partition}",
        "\\centering",
        "\\small",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{lrrrrr}",
        "\\toprule",
        "Policy & Vert.\\ rep. & Edge rep. & Imbal. & $C_{\\mathrm{edg}}$ (MB) & Hit\\\\",
        "\\midrule",
    ])
    for key in partition_keys:
        row = summary[f"partition-policy|{key}"]
        edge_mb = float(row["C_edg_bytes_mean"]) / 1e6
        lines.append(
            f"{key} & {number(row, 'replication_factor_vertices')} & "
            f"{number(row, 'replication_factor_edges')} & "
            f"{number(row, 'load_imbalance')} & {edge_mb:.2f} & "
            f"{number(row, 'cache_hit_rate')}\\\\"
        )
    lines.extend([
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
        "\\begin{table}[t]",
        "\\caption{Trace-level component ablation. Pipeline affects execution overlap, "
        "not access bytes, so +RCS and +RCSP have identical trace-level traffic.}",
        "\\label{tbl:real-component}",
        "\\centering",
        "\\small",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "Configuration & Vert.\\ rep. & Imbal. & $C_{\\mathrm{edg}}$ (MB) & Hit rate\\\\",
        "\\midrule",
    ])
    for key in component_keys:
        row = summary[f"component-ablation|{key}"]
        edge_mb = float(row["C_edg_bytes_mean"]) / 1e6
        lines.append(
            f"{key} & {number(row, 'replication_factor_vertices')} & "
            f"{number(row, 'load_imbalance')} & {edge_mb:.2f} & "
            f"{ci(row, 'cache_hit_rate')}\\\\"
        )
    lines.extend([
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
        "\\begin{table}[t]",
        "\\caption{Sensitivity of EDGaE's partition score on the real topology.}",
        "\\label{tbl:real-score-sensitivity}",
        "\\centering",
        "\\small",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "Weights & Vert.\\ rep. & Edge rep. & Imbalance & $C_{\\mathrm{edg}}$ (MB)\\\\",
        "\\midrule",
    ])
    for key in score_keys:
        row = summary[f"score-sensitivity|{key}"]
        edge_mb = float(row["C_edg_bytes_mean"]) / 1e6
        lines.append(
            f"{key} & {number(row, 'replication_factor_vertices')} & "
            f"{number(row, 'replication_factor_edges')} & "
            f"{number(row, 'load_imbalance')} & {edge_mb:.2f}\\\\"
        )
    lines.extend([
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("summary", nargs="?", default="www2027-real-trace-summary-v2.csv")
    parser.add_argument("output", nargs="?", default="www2027-real-trace-tables.tex")
    args = parser.parse_args()
    summary = load_summary(Path(args.summary))
    Path(args.output).write_text(make_table(summary), encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

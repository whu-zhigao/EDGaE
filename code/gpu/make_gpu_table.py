#!/usr/bin/env python3
"""Generate ICDE/tab-gpu-native.tex from returned GPU results."""
import csv, statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
rows = list(csv.DictReader(open(ROOT / "gpu_experiments/results/gpu_native_results.csv")))
gcn = [r for r in rows if r["experiment"] == "E1_fullbatch_gcn"]
srv = [r for r in rows if r["experiment"] == "E2_E3_sage" and r["mode"] == "server"]
edg = [r for r in rows if r["experiment"] == "E2_E3_sage" and r["mode"] == "edgae"]
f4 = [r for r in rows if r["mode"] == "edgae_f4"]
f8 = [r for r in rows if r["mode"] == "edgae_f8"]

def mean(rs, f): return st.mean(float(r[f]) for r in rs)
parity = max(abs(float(s["best_val"]) - float(e["best_val"]))
             for s, e in zip(srv, edg))
miss_ep = lambda rs: mean(rs, "miss_bytes") / float(rs[0]["epochs"]) / 1e6

lines = [
  r"\texttt{GCN} full-batch (ref.) & %.1f\,$\pm$\,%.1f & -- & --\\" % (
    100*mean(gcn, "test_acc"), 100*st.stdev([float(r["test_acc"]) for r in gcn])),
  r"\texttt{SAGE} host-fetch, $f{=}2$ & %.1f & -- & %.0f\\" % (
    100*mean(srv, "test_acc"), miss_ep(srv)),
  r"\texttt{SAGE} GPU-cache, $f{=}2$ & %.1f & %.4f & %.0f\\" % (
    100*mean(edg, "test_acc"), parity, miss_ep(edg)),
  r"\texttt{SAGE} GPU-cache, $f{=}4$ & %.1f & -- & %.0f\\" % (
    100*mean(f4, "test_acc"), miss_ep(f4)),
  r"\texttt{SAGE} GPU-cache, $f{=}8$ & %.1f & -- & %.0f\\" % (
    100*mean(f8, "test_acc"), miss_ep(f8)),
]
(ROOT / "ICDE/tab-gpu-native.tex").write_text(
  "% AUTO-GENERATED by gpu_experiments/make_gpu_table.py\n"
  "\\begin{tabular}{@{}lrrr@{}}\n\\toprule\n"
  "Configuration & Test (\\%) & Parity $|\\Delta\\text{val}|$ & Miss/epoch (MB)\\\\\n"
  "\\midrule\n" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n")
print("parity:", parity, "| byte/epoch:", miss_ep(srv), miss_ep(edg))
